import { useEffect, useMemo, useState } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import Navbar from '../components/Navbar.jsx';

// Port of result.js + result.html

function readResult() {
  try {
    return JSON.parse(localStorage.getItem('examResult'));
  } catch (e) {
    return null;
  }
}

export default function Result() {
  const navigate = useNavigate();
  const result = useMemo(readResult, []);

  const score = result ? result.percentage : 0;
  const ai = result ? result.feedback : null;

  const [current, setCurrent] = useState(0);

  useEffect(() => {
    if (!result) {
      alert('No exam result found.');
      navigate('/', { replace: true });
    }
  }, []); // eslint-disable-line

  // =============================
  // Animate Score
  // =============================
  useEffect(() => {
    if (!result) return undefined;

    let cur = 0;
    const duration = 1000;
    const stepTime = 16;
    const steps = duration / stepTime;
    const increment = score / steps;

    const timer = setInterval(() => {
      cur += increment;

      if (cur >= score) {
        cur = score;
        clearInterval(timer);
      }

      setCurrent(cur);
    }, stepTime);

    return () => clearInterval(timer);
  }, [result, score]);

  if (!result) return null;

  const topicsCovered = [...new Set((result.questions || []).map((q) => q.topic))].length;
  const high = score >= 70;

  // =============================
  // Download Report
  // =============================
  const downloadReport = async () => {
    const { jsPDF } = await import('jspdf'); // loaded only when needed
    const doc = new jsPDF();

    let y = 20;

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(20);
    doc.text('GemmaTutor AI', 20, y);

    y += 8;

    doc.setFontSize(15);
    doc.text('Student Performance Report', 20, y);

    y += 10;

    doc.line(20, y, 190, y);

    y += 10;

    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');

    doc.text(`Date : ${new Date().toLocaleDateString()}`, 20, y);
    y += 7;

    doc.text(`Chapter : ${result.chapter || 'Uploaded PDF'}`, 20, y);
    y += 7;

    doc.text(`Time Taken : ${result.timeTaken}`, 20, y);

    y += 10;

    doc.line(20, y, 190, y);

    y += 10;

    doc.setFont('helvetica', 'bold');
    doc.text('Exam Summary', 20, y);

    y += 8;

    doc.setFont('helvetica', 'normal');

    doc.text(`Score : ${result.correct}/${result.totalQuestions}`, 25, y);
    y += 7;

    doc.text(`Percentage : ${result.percentage}%`, 25, y);
    y += 7;

    doc.text(`Grade : ${result.grade}`, 25, y);

    y += 10;

    doc.line(20, y, 190, y);

    y += 10;

    doc.setFont('helvetica', 'bold');
    doc.text('AI Feedback', 20, y);

    y += 8;

    doc.setFont('helvetica', 'normal');

    const feedback = doc.splitTextToSize(ai.feedback, 170);

    doc.text(feedback, 20, y);

    y += feedback.length * 6 + 8;

    doc.line(20, y, 190, y);

    y += 8;

    doc.setFont('helvetica', 'bold');
    doc.text('Strengths', 20, y);

    y += 7;

    doc.setFont('helvetica', 'normal');

    ai.strengths.forEach((item) => {
      doc.text('• ' + item, 25, y);
      y += 6;
    });

    y += 5;

    doc.setFont('helvetica', 'bold');
    doc.text('Weak Topics', 20, y);

    y += 7;

    doc.setFont('helvetica', 'normal');

    ai.weak_topics.forEach((item) => {
      doc.text('• ' + item, 25, y);
      y += 6;
    });

    y += 5;

    doc.setFont('helvetica', 'bold');

    if (result.percentage >= 70) {
      doc.text('Recommended Next Topics', 20, y);

      y += 7;

      doc.setFont('helvetica', 'normal');

      ai.recommended_topics.forEach((item) => {
        doc.text('• ' + item, 25, y);
        y += 6;
      });
    } else {
      doc.text('Recommended Learning Videos', 20, y);

      y += 7;

      doc.setFont('helvetica', 'normal');

      ai.youtube_videos.forEach((video) => {
        doc.text('• ' + video.title, 25, y);
        y += 6;
      });
    }

    y += 8;

    doc.line(20, y, 190, y);

    y += 10;

    doc.setFontSize(10);

    doc.text('Generated by GemmaTutor AI', 20, y);
    doc.line(20, y, 190, y);

    y += 10;

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);

    doc.text('Question Review', 20, y);

    y += 10;

    // =============================
    // Question Review
    // =============================
    result.review_questions.forEach((q, index) => {
      // ---------------------------
      // Calculate card height
      // ---------------------------
      const questionLines = doc.splitTextToSize(q.question, 165);

      const explanationLinesForHeight = q.explanation
        ? doc.splitTextToSize('Explanation: ' + q.explanation, 160)
        : [];

      // Estimated height
      const cardHeight =
        35 +
        questionLines.length * 6 +
        q.options.length * 8 +
        explanationLinesForHeight.length * 6;

      // New page if card won't fit
      if (y + cardHeight > 270) {
        doc.addPage();
        y = 20;
      }

      // -------------------------
      // Question Heading
      // -------------------------
      // Card Border
      doc.setDrawColor(220);
      doc.setFillColor(252, 252, 252);

      doc.roundedRect(15, y - 5, 180, cardHeight, 4, 4, 'FD');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);

      doc.text(`Question ${index + 1}`, 20, y);

      y += 8;

      doc.setFont('helvetica', 'normal');

      doc.text(questionLines, 20, y);

      y += questionLines.length * 6 + 5;

      // -------------------------
      // Options
      // -------------------------
      q.options.forEach((option, optionIndex) => {
        let prefix = '   ';

        // Correct Answer
        if (optionIndex === q.correct_answer) {
          prefix = '✓ ';
          doc.setTextColor(0, 150, 0);
        }

        // Student selected wrong answer
        else if (
          optionIndex === q.student_answer &&
          q.student_answer !== q.correct_answer
        ) {
          prefix = '✗ ';
          doc.setTextColor(220, 0, 0);
        } else {
          doc.setTextColor(0, 0, 0);
        }

        const letter = String.fromCharCode(65 + optionIndex);

        const optionLines = doc.splitTextToSize(`${prefix}${letter}. ${option}`, 165);

        doc.text(optionLines, 25, y);

        y += optionLines.length * 6;
      });

      // -------------------------
      // Explanation
      // -------------------------
      if (q.explanation) {
        y += 2;

        doc.setTextColor(70, 70, 70);

        doc.setFont('helvetica', 'italic');

        const explanationLines = doc.splitTextToSize('Explanation: ' + q.explanation, 165);

        doc.text(explanationLines, 25, y);

        y += explanationLines.length * 6;

        doc.setFont('helvetica', 'normal');
      }

      doc.setTextColor(0, 0, 0);

      y += 8;

      doc.line(20, y, 190, y);

      y += 10;
    });

    doc.line(20, y, 190, y);

    y += 10;

    doc.setFontSize(10);

    doc.text('Generated by GemmaTutor AI', 20, y);

    doc.text(new Date().toLocaleString(), 120, y);

    doc.save('GemmaTutor_AI_Report.pdf');
  };

  return (
    <>
      {/* ============ NAVBAR ============ */}
      <Navbar>
        <ul className="navbar-nav ms-auto align-items-lg-center gap-lg-1">
          <li className="nav-item"><Link className="nav-link gt-nav-link" to="/">Home</Link></li>
          <li className="nav-item"><Link className="nav-link gt-nav-link active" to="/result">Results</Link></li>
        </ul>
      </Navbar>

      <main className="gt-section" style={{ paddingTop: '8rem' }}>
        <div className="container">

          <div className="text-center mb-5">
            <span className="gt-step-pill mb-3"><i className="bi bi-3-circle-fill"></i> Step 3 of 3 — Results</span>
            <h2 className="mt-3 mb-1">Your exam results</h2>
            <p className="text-muted-soft" id="chapterTitle">
              {result.chapter || 'Uploaded PDF'}
            </p>
          </div>
          <svg className="gemma-svg gemma-svg-6" viewBox="0 0 100 100" fill="none" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">
            <circle cx="50" cy="50" r="46" stroke="#000000" strokeWidth="1.5" strokeDasharray="4 6" />
            <circle cx="50" cy="50" r="30" stroke="#000000" strokeWidth="1.5" />
          </svg>
          <svg className="gemma-svg gemma-svg-5" viewBox="0 0 100 100" fill="none" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">
            <rect x="10" y="10" width="80" height="80" rx="18" stroke="#000000" strokeWidth="1.5" />
            <path d="M30 50h40M30 65h24" stroke="#000000" strokeWidth="1.5" strokeLinecap="round" />
          </svg>

          <div className="row g-4 align-items-stretch mb-4">
            {/* Score ring */}
            <div className="col-lg-4">
              <div className="gt-card text-center h-100 d-flex flex-column justify-content-center">
                <div className="gt-score-ring" id="scoreRing" style={{ '--pct': current }}>
                  <div className="gt-score-ring-inner">
                    <div>
                      <div className="gt-score-value"><span id="scoreValue">{Math.round(current)}</span>%</div>
                      <div className="text-muted-soft small">Overall score</div>
                    </div>
                  </div>
                </div>
                <div className="mt-3">
                  {high ? (
                    <span className="gt-badge-soft-success" id="scoreBadge">
                      <i className="bi bi-arrow-up-short"></i> Great Performance
                    </span>
                  ) : (
                    <span className="gt-badge-soft-warn" id="scoreBadge">
                      <i className="bi bi-arrow-down-short"></i> Needs Improvement
                    </span>
                  )}
                </div>
              </div>
            </div>

            {/* Stats */}
            <div className="col-lg-8">
              <div className="row g-3 h-100">
                <div className="col-6 col-md-3">
                  <div className="gt-stat-card h-100">
                    <div className="val" id="correctAnswers">{`${result.correct}/${result.totalQuestions}`}</div>
                    <div className="lbl">Correct answers</div>
                  </div>
                </div>
                <div className="col-6 col-md-3">
                  <div className="gt-stat-card h-100">
                    <div className="val mono" id="timeTaken">{result.timeTaken || '--'}</div>
                    <div className="lbl">Time taken</div>
                  </div>
                </div>
                <div className="col-6 col-md-3">
                  <div className="gt-stat-card h-100">
                    <div className="val" id="topicsCovered">{topicsCovered}</div>
                    <div className="lbl">Topics covered</div>
                  </div>
                </div>
                <div className="col-6 col-md-3">
                  <div className="gt-stat-card h-100">
                    <div className="val" id="gradeValue">{result.grade}</div>
                    <div className="lbl">Grade</div>
                  </div>
                </div>
                <div className="col-12">
                  <div className="gt-feedback-card h-100">
                    <i className="bi bi-quote"></i>
                    <p className="mb-0 mt-2" id="feedbackText">
                      {ai ? ai.feedback : 'Loading AI feedback...'}
                    </p>
                  </div>
                </div>
              </div>
            </div>
          </div>

          <div className="row g-4">
            {/* Strengths */}
            <div className="col-md-6">
              <div className="gt-card h-100">
                <div className="d-flex align-items-center gap-2 mb-3">
                  <div className="gt-icon-badge mb-0" style={{ width: 42, height: 42, fontSize: '1.1rem' }}><i className="bi bi-hand-thumbs-up-fill"></i></div>
                  <h5 className="mb-0">Strengths</h5>
                </div>
                <ul className="list-unstyled gt-list-check mb-0" id="strengthList">
                  {ai && (ai.strengths || []).map((item, i) => (
                    <li key={i}>
                      <i className="bi bi-check-circle-fill"></i>
                      {' '}{item}
                    </li>
                  ))}
                </ul>
              </div>
            </div>

            {/* Weak topics */}
            <div className="col-md-6">
              <div className="gt-card h-100">
                <div className="d-flex align-items-center gap-2 mb-3">
                  <div className="gt-icon-badge mb-0" style={{ width: 42, height: 42, fontSize: '1.1rem' }}><i className="bi bi-flag-fill"></i></div>
                  <h5 className="mb-0">Weak topics</h5>
                </div>
                <ul className="list-unstyled gt-list-warn mb-0" id="weakTopicList">
                  {ai && (ai.weak_topics || []).map((item, i) => (
                    <li key={i}>
                      <i className="bi bi-exclamation-triangle-fill"></i>
                      {' '}{item}
                    </li>
                  ))}
                </ul>
              </div>
            </div>

            {/* Recommended next topics (shown when score is high) */}
            <div className={'col-12' + (high ? '' : ' d-none')} id="nextTopicsSection">
              <div className="gt-card">
                <div className="d-flex align-items-center gap-2 mb-3">
                  <div className="gt-icon-badge mb-0" style={{ width: 42, height: 42, fontSize: '1.1rem' }}><i className="bi bi-signpost-split-fill"></i></div>
                  <h5 className="mb-0">Recommended next topics</h5>
                </div>
                <p className="text-muted-soft small mb-3">You're ready to move on — here's what builds naturally on this chapter.</p>
                <div className="d-flex flex-wrap gap-2" id="nextTopics">
                  {ai && (ai.recommended_topics || []).map((item, i) => (
                    <span className="gt-topic-pill" key={i}>
                      <i className="bi bi-arrow-right-short"></i>
                      {' '}{item}
                    </span>
                  ))}
                </div>
              </div>
            </div>

            {/* Revision suggestions (shown when score is low) */}
            <div className={'col-12' + (high ? ' d-none' : '')} id="revisionSection">
              <div className="gt-card">
                <div className="d-flex align-items-center gap-2 mb-3">
                  <div className="gt-icon-badge mb-0" style={{ width: 42, height: 42, fontSize: '1.1rem' }}><i className="bi bi-arrow-repeat"></i></div>
                  <h5 className="mb-0">Revision suggestions</h5>
                </div>
                <p className="text-muted-soft small mb-3">Focus your next study session on these before retaking the exam.</p>
                <div className="d-flex flex-wrap gap-2" id="revisionTopics">
                  {ai && (
                    ai.youtube_videos && ai.youtube_videos.length > 0 ? (
                      <div className="gt-video-list">
                        {ai.youtube_videos.map((video, i) => {
                          const url = `https://www.youtube.com/results?search_query=${encodeURIComponent(video.search_query)}`;
                          return (
                            <div className="gt-video-card" key={i}>
                              <div className="gt-video-icon">
                                <i className="bi bi-youtube"></i>
                              </div>

                              <div className="gt-video-body">
                                <p className="gt-video-title">{video.title}</p>
                                <span className="gt-video-sub">Recommended video</span>
                              </div>

                              <a href={url} target="_blank" rel="noopener noreferrer" className="gt-video-action">
                                <i className="bi bi-play-circle"></i>
                                {' '}Watch
                              </a>
                            </div>
                          );
                        })}
                      </div>
                    ) : (
                      (ai.weak_topics || []).map((item, i) => (
                        <span className="gt-topic-pill" key={i}>
                          <i className="bi bi-book"></i>
                          {' '}{item}
                        </span>
                      ))
                    )
                  )}
                </div>
              </div>
            </div>
          </div>

          <div className="d-flex flex-column flex-sm-row justify-content-center gap-3 mt-5">
            <button className="btn btn-gt-primary btn-lg" id="downloadBtn" onClick={downloadReport}>
              <i className="bi bi-download me-2"></i>Download Report
            </button>
            <Link to="/upload" className="btn btn-gt-outline btn-lg">
              <i className="bi bi-arrow-repeat me-2"></i>Take another exam
            </Link>
          </div>

        </div>
      </main>

      <footer className="gt-footer mt-5">
        <div className="container text-center small">
          &copy; 2026 GemmaTutor AI.
          All rights reserved.
          AI-generated learning report.
        </div>
      </footer>
    </>
  );
}
